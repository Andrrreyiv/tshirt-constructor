// Ширина поля, в котором показывается футболка. Клиент 01.08 (голос + видео):
// «я бы ещё больше увеличил, чтобы вообще по краям отступов не было… принты очень
// маленькие, человек что-то вставит и не поймёт, красиво или нет», и следом:
// «мне нужно вот это поле, вот это поле самой формы увеличить прямо до краёв».
//
// ⚠️ Почему это ОТДЕЛЬНАЯ ручка, а не кадрирование. Кадр («Увеличить футболку») режет
// пустые поля вокруг изделия и упирается в то, сколько этих полей есть: замер мокапа
// на боевом — футболка занимает 76.8% ширины файла и 88.3% высоты, то есть запас всего
// ~1.25x, дальше кадр режет сами рукава и низ. Плюс кадр обязан вмещать зону печати
// (cropFitsZones), поэтому чем больше владелец делает зону, тем МЕНЬШЕ может увеличить
// футболку. Ручка ширины поля от этих потолков свободна: она растягивает саму сцену,
// изделие при этом не обрезается.
//
// Значение — максимальная ширина макета (#app) в пикселях. На экране уже этого числа
// правило просто не срабатывает, поэтому мобильную раскладку ручка не трогает.

/** Ширина макета по умолчанию — как в CSS (#app max-width). */
export const DEFAULT_STAGE_WIDTH = 1200;

/** Ниже панель справа (372px) начинает съедать сцену. Выше строка ведёт глаз слишком далеко. */
export const MIN_STAGE_WIDTH = 1000;
export const MAX_STAGE_WIDTH = 2000;

/** Зажать ширину в рабочий диапазон. Дробные пиксели ни к чему, округляем. */
export function clampStageWidth(value) {
  // ⚠️ Number(null) и Number('') дают 0, а не NaN, поэтому пустые значения приходится
  // отсеивать ДО приведения: иначе "настройки не заданы" молча превращалось бы
  // в самое узкое поле вместо ширины по умолчанию.
  if (value === null || value === undefined || value === '') return DEFAULT_STAGE_WIDTH;
  const n = Number(value);
  if (!Number.isFinite(n)) return DEFAULT_STAGE_WIDTH;
  return Math.round(Math.min(Math.max(n, MIN_STAGE_WIDTH), MAX_STAGE_WIDTH));
}

/**
 * Разбор значения из файла настроек (stage.json) или из POST админки.
 * Мусор и выход за диапазон дают null: вызывающий молча остаётся на ширине из CSS,
 * как это уже делают zones.json и crops.json.
 */
export function validateStageWidth(v) {
  // ⚠️ Массив сюда попасть не должен, и молча пропустить его нельзя: Number([1400])
  // в JS даёт 1400, поэтому [1400] прошло бы как валидная настройка.
  if (Array.isArray(v)) return null;
  const raw = (v && typeof v === 'object') ? v.width : v;
  if (raw === null || raw === undefined || raw === '') return null;
  const n = Number(raw);
  if (!Number.isFinite(n)) return null;
  if (n < MIN_STAGE_WIDTH || n > MAX_STAGE_WIDTH) return null;
  return Math.round(n);
}

/**
 * Новая ширина при перетаскивании ручки. Ручка живёт на ПРАВОМ крае поля, а поле
 * центрировано в окне, поэтому сдвиг курсора на dx двигает только одну его сторону:
 * ширина меняется на 2*dx, иначе изделие отставало бы от курсора вдвое.
 */
export function widthFromDrag(startWidth, dx) {
  return clampStageWidth(startWidth + dx * 2);
}
