// PrintMethod — метод нанесения выводится из того, что покупатель положил на футболку,
// а не выбирается вручную.
//
// Клиент 25.08: «мы же не можем плёнкой сделать такой принт, поэтому не надо ему выбора
// такой ошибочный давать, она плёнкой дешевле, они будут тыкать плёнкой, а потом лишнее
// объяснять им, что это на самом деле плёнкой не получится».

export function forcedMethod({ hasPrint = false, hasText = false } = {}) {
  if (hasPrint) return 'dtf';
  if (hasText) return 'film';
  return null;
}
