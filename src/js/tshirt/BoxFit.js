// Вписывание рамки принта в зону печати.
// Клиент 28.07: «логотипы, цифры — отступы от рамок, я не могу к краям раздвинуть».
// Причина была в том, что ширина ограничивалась остатком справа (1 - fx): принт вставляется
// по центру (fx≈0.075), поэтому потолок ширины выходил ≈0.92 зоны — на экране «37×50» вместо 40×50.
// Теперь размер ограничен САМОЙ зоной, а если правый/нижний край упёрся — принт сдвигается внутрь.
// Все величины — доли зоны печати (0..1), зона = 1×1.
export function fitBoxInFrame({ fx, fy, fw, fh }) {
  const w = clamp(fw, 0, 1);
  const h = clamp(fh, 0, 1);
  return {
    fx: clamp(fx, 0, 1 - w),
    fy: clamp(fy, 0, 1 - h),
    fw: w,
    fh: h
  };
}

function clamp(v, lo, hi) {
  return Math.min(Math.max(v, lo), hi);
}
