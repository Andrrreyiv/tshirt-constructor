// Дефект клиента 25.08 (голос 15-09-19), дословно:
// «если человек просто надпись выбрал, то там делаем плёнкой… кнопку плёнкой, и всё,
// ничем поменять не может, не может поменять на DTF. Если он выбрал принт или загрузил
// картинку, то там делаем только DTF, там кнопку плёнка убираем. Если он совместно
// сделал и принт и надпись, то тоже только DTF… она плёнкой дешевле, они будут тыкать
// плёнкой, а потом лишнее объяснять им, что это на самом деле плёнкой не получится».
//
// То есть выбор метода это не свобода покупателя, а следствие того, что он положил.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { forcedMethod } from '../src/js/tshirt/PrintMethod.js';

test('только надпись — плёнка', () => {
  assert.equal(forcedMethod({ hasPrint: false, hasText: true }), 'film');
});

// «если он выбрал принт или загрузил картинку, то там делаем только DTF».
test('принт на футболке — только DTF', () => {
  assert.equal(forcedMethod({ hasPrint: true, hasText: false }), 'dtf');
});

// «если он совместно сделал и принт и надпись, то тоже только DTF».
test('принт вместе с надписью — тоже DTF', () => {
  assert.equal(forcedMethod({ hasPrint: true, hasText: true }), 'dtf');
});

// На пустой футболке метода нет вообще: показывать нечего, и цена печати нулевая.
// Возвращаем null, а не 'dtf', чтобы вызывающая сторона могла скрыть поле целиком.
test('на пустой футболке метода нет', () => {
  assert.equal(forcedMethod({ hasPrint: false, hasText: false }), null);
});
