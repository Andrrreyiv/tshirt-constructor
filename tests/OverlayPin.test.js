// Дефект клиента 25.08 (видео): «Видишь, ползёт вниз, вот этот экран. Он ползёт, ползёт
// и он ползёт до бесконечности».
//
// Конструктор стоит на сайте в iframe БЕЗ своей прокрутки: скрипт страницы подгоняет высоту
// рамки под высоту документа. Окно библиотеки принтов позиционировалось `absolute` и каждый
// кадр сдвигалось вниз на величину прокрутки (`top = -box.top`). Абсолютный элемент входит
// в `scrollHeight`, поэтому документ становился выше → сайт увеличивал iframe → рамка уезжала
// выше → следующий кадр сдвигал окно ещё ниже. Петля на 60 кадрах в секунду, вниз без конца.
//
// Лечение: `fixed`. Внутри iframe своей прокрутки нет (scrollY всегда 0), поэтому на экране
// окно встаёт РОВНО туда же, но в высоту документа больше не входит и петлю кормить нечем.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { pinStyle } from '../src/js/tshirt/LibraryPanel.js';

test('окно библиотеки не входит в высоту документа', () => {
  // Рамку прокрутили так, что её верх ушёл на 800px выше экрана.
  const style = pinStyle({ top: -800, bottom: 2400 }, 900);
  assert.equal(style.position, 'fixed');
});

// Смысл всей затеи: окно стоит на ВИДИМОЙ части рамки, а не по середине конструктора.
// Прокрутки внутри iframe нет (scrollY всегда 0), поэтому `fixed` с этим же top
// даёт на экране ровно то же место, что давал прежний `absolute`.
test('окно ложится на видимую часть рамки', () => {
  const style = pinStyle({ top: -800, bottom: 2400 }, 900);
  assert.equal(style.top, 800);   // верх рамки ушёл на 800px вверх
  assert.equal(style.height, 900); // видно ровно экран покупателя
});

// ⚠️ Вторая, ГЛАВНАЯ причина того же дефекта, найдена замером на стенде 25.08 уже ПОСЛЕ
// правки окна библиотеки: страница ползла вниз сама, без всякой библиотеки, ровно на 16px
// за кадр, без конца (замер: 3766 → 3782 → 3798 → 3814 → …).
//
// Механика петли целиком в одной строке CSS. У body стояло `min-height: 100vh`, а внутри
// iframe `100vh` это высота САМОЙ РАМКИ. Скрипт сайта ставит рамке высоту документа, документ
// сразу дотягивается min-height до новой высоты рамки, `documentElement.scrollHeight` всегда
// на 16px больше body — и следующий кадр добавляет ещё 16. Замер подтвердил обе стороны:
// с `min-height: auto` рост за 118 замеров равен 0, с `100vh` он бесконечен.
//
// Убрать её можно без потерь: фон body по правилам CSS и так закрашивает весь холст
// (у html своего фона нет), а содержимое конструктора выше любого экрана.
test('высота документа не привязана к высоте рамки', () => {
  // Комментарии вырезаем: в самом CSS рядом с правкой объяснено, почему `100vh` нельзя
  // возвращать, и без этого шага тест ловил бы собственное объяснение.
  const css = readFileSync(new URL('../src/css/app.css', import.meta.url), 'utf8')
    .replace(/\/\*[\s\S]*?\*\//g, '');
  const body = /(^|\})\s*body\s*\{([^}]*)\}/m.exec(css);
  assert.ok(body, 'правило body не найдено');
  assert.doesNotMatch(
    body[2],
    /(min-)?height\s*:[^;]*vh/,
    'высота body в vh: внутри iframe это высота рамки, и рамка растёт от себя самой',
  );
});
